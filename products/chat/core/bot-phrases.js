/** Every built-in phrase of every language, in one list. */
const BUILT_IN = Object.freeze(Object.values(BOT_PHRASES).flat());

/**
 * The phrases to look for in an answer: the built-in ones of every language and the merchant's own (Settings).
 * @param {unknown} [extra] the merchant's phrases (anything else is ignored)
 * @returns {readonly string[]}
 */
export const botPhrases = (extra) => {
	const own = Array.isArray(extra) ? extra.filter((phrase) => typeof phrase === 'string' && phrase.trim() !== '') : [];
	return own.length === 0 ? BUILT_IN : [...BUILT_IN, ...own];
};
